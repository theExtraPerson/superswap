// Typed member-side client for the /api routes. Every rule (minimums, fees,
// windows, the reserve gate) is enforced inside app_* RPCs — this module is
// plumbing, never policy.

import { apiRequest, post, type ApiConfig } from "@/lib/api/client";
import type {
  AuthResult,
  CheckinResult,
  DashboardPayload,
  OpenDepositResult,
  ProfileRow,
  PublicInfoPayload,
  SignupBonusResult,
  TeamPayload,
  CycleRow,
  WithdrawalRow,
} from "@/lib/api/types";

// ---------- public reads ----------
export const getPublicInfo = (cfg: ApiConfig = {}) =>
  apiRequest<PublicInfoPayload>("/info", { method: "GET" }, cfg);

// ---------- auth ----------
export const register = (
  input: {
    fullName: string;
    username: string;
    phone: string;
    password: string;
    referralCode?: string;
  },
  cfg: ApiConfig = {}
) => apiRequest<AuthResult>("/auth/register", post(input), cfg);

export const login = (input: { username: string; password: string }, cfg: ApiConfig = {}) =>
  apiRequest<AuthResult>("/auth/login", post(input), cfg);

export const changePassword = (input: { password: string }, cfg: ApiConfig = {}) =>
  apiRequest<{ updated: boolean }>("/auth/password", post(input), cfg);

export const getMe = (cfg: ApiConfig = {}) =>
  apiRequest<{ profile: ProfileRow }>("/me", { method: "GET" }, cfg);

// ---------- member reads ----------
export const getDashboard = (cfg: ApiConfig = {}) =>
  apiRequest<DashboardPayload>("/dashboard", { method: "GET" }, cfg);
export const getTeam = (cfg: ApiConfig = {}) =>
  apiRequest<TeamPayload>("/team", { method: "GET" }, cfg);

/**
 * One-time welcome bonus. The server claim is replay-safe, so calling it when
 * the desk already credited the bonus simply reports `already_claimed`.
 */
export const claimWelcomeBonus = (cfg: ApiConfig = {}) =>
  apiRequest<SignupBonusResult>("/bonus/welcome", { method: "POST" }, cfg);

/**
 * Daily check-in (app_checkin). Replay-safe per platform day in SQL: the first
 * call of the day credits the setting amount, later calls report already_claimed.
 */
export const dailyCheckin = (cfg: ApiConfig = {}) =>
  apiRequest<CheckinResult>("/checkin", { method: "POST" }, cfg);

// ---------- member writes (idempotency keys generated by the caller) ----------
export const openVault = (
  input: { productId: number; principal: number; idemKey?: string },
  cfg: ApiConfig = {}
) => apiRequest<CycleRow>("/vaults/open", post(input), cfg);

export const exitVault = (cycleId: number, cfg: ApiConfig = {}) =>
  apiRequest<CycleRow>("/vaults/exit", post({ cycleId }), cfg);

export const openDeposit = (
  input: {
    amount: number;
    channel: "momo" | "bank";
    payerAccount: string;
    reference?: string;
    idemKey?: string;
  },
  cfg: ApiConfig = {}
) => apiRequest<OpenDepositResult>("/deposits", post(input), cfg);

export const openWithdrawal = (
  input: {
    amount: number;
    channel: "momo" | "bank";
    destinationAccount: string;
    idemKey?: string;
  },
  cfg: ApiConfig = {}
) => apiRequest<WithdrawalRow>("/withdrawals", post(input), cfg);

/** Client-side idempotency key (uuid): retries can never double-apply. */
export const newIdemKey = (prefix: string) =>
  `${prefix}:${typeof crypto !== "undefined" ? crypto.randomUUID() : Math.random().toString(36).slice(2)}`;
